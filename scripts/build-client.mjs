// Build the browser module from small, ordered source fragments. No dependencies.
// Usage: node scripts/build-client.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";

const sources = [
    "runtime.js",
    "options.js",
    "subscription-catalog.js",
    "quota.js",
    "deepseek-balance.js",
    "balance-card.js",
    "quota-settings.js",
    "styles.js",
    "apply.js"
];
const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const subscriptionCatalog = read("subscriptions.json");
const body = sources.map((file) => {
    const content = read(`client/${file}`).replace(/\r\n/g, "\n").trim()
        .replace("__SUBSCRIPTION_CATALOG__", subscriptionCatalog);
    return `        //#region client/${file}\n${content}\n        //#endregion`;
}).join("\n\n");
const generated = `// Generated by scripts/build-client.mjs. Edit client/*.js instead.\nwindow.__ModuleLoader__.load({\n    id: "dsh-subscription-management",\n    factory: (require) => {\n${body}\n        return module.exports;\n    }\n});\n`;
const target = new URL("../client.js", import.meta.url);
if (process.argv.includes("--check")) {
    const current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
    if (current !== generated) {
        console.error("client.js is stale; run node scripts/build-client.mjs");
        process.exitCode = 1;
    } else {
        console.log("client.js is up to date");
    }
} else {
    writeFileSync(target, generated, "utf8");
    console.log(`built client.js from ${sources.length} modules`);
}
